#!/usr/bin/env python3
"""Regenerate log.md from the Git commit history.

Commit message convention
-------------------------
Subject line:  [HH:MM] Title                      (same-day session)
               [YYYY-MM-DD--HH:MM] Title          (multi-day session)
Body lines starting with "- " become bullet points.

The end of the session is the commit timestamp (Europe/Madrid). The start is
read from the square brackets at the beginning of the subject line.

log.md is AUTO-GENERATED. Never edit it by hand: change this script instead.
Commit messages may use inline Markdown (for example `code`).
"""

from __future__ import annotations

import re
import subprocess
import sys
from dataclasses import dataclass, field
from datetime import datetime, timedelta
from pathlib import Path

try:
    from zoneinfo import ZoneInfo

    TZ = ZoneInfo("Europe/Madrid")
except Exception as exc:  # pragma: no cover
    sys.exit(
        "Timezone database not available. On Windows run: pip install tzdata\n"
        f"Details: {exc}"
    )

ROOT = Path(__file__).resolve().parent
OUTPUT = ROOT / "log.md"

# Commits made by the workflow itself are never logged as work sessions.
BOT_AUTHORS = {"github-actions[bot]"}
SKIPPED_SUBJECT_PREFIXES = ("[skip ci]", "Update work log")

SUBJECT_RE = re.compile(r"^\[(?P<start>[^\]]+)\]\s*(?P<title>.*)$")
TIME_RE = re.compile(r"^\d{1,2}:\d{2}$")
DATETIME_RE = re.compile(r"^(\d{4}-\d{2}-\d{2})--(\d{1,2}:\d{2})$")

@dataclass
class Session:
    end: datetime
    start: datetime | None
    title: str
    items: list[str] = field(default_factory=list)


def resolve_start(raw: str, end: datetime) -> datetime | None:
    """Turn the bracket content into a datetime, or None if unrecognised."""
    raw = raw.strip()
    if TIME_RE.fullmatch(raw):
        hour, minute = (int(part) for part in raw.split(":"))
        start = end.replace(hour=hour, minute=minute, second=0, microsecond=0)
        if start > end:  # session crossed midnight
            start -= timedelta(days=1)
        return start
    match = DATETIME_RE.fullmatch(raw)
    if match:
        return datetime.strptime(
            f"{match.group(1)} {match.group(2)}", "%Y-%m-%d %H:%M"
        ).replace(tzinfo=TZ)
    return None


def read_sessions() -> list[Session]:
    fmt = "%x1e%an%x1f%aI%x1f%B"
    result = subprocess.run(
        ["git", "log", "--reverse", "--no-merges", f"--format={fmt}"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        encoding="utf-8",
        check=True,
    )
    sessions: list[Session] = []
    for record in result.stdout.split("\x1e"):
        record = record.lstrip("\n")
        if not record.strip():
            continue
        author, iso_date, message = record.split("\x1f", 2)
        lines = message.strip().splitlines()
        if not lines:
            continue
        subject = lines[0].strip()
        if author in BOT_AUTHORS or subject.startswith(SKIPPED_SUBJECT_PREFIXES):
            continue

        end = datetime.fromisoformat(iso_date).astimezone(TZ)
        match = SUBJECT_RE.match(subject)
        if match:
            start = resolve_start(match.group("start"), end)
            title = match.group("title").strip()
        else:
            start, title = None, subject
        items = [ln[2:].strip() for ln in lines[1:] if ln.startswith("- ")]
        sessions.append(Session(end, start, title or "Untitled session", items))
    return sessions


def format_duration(start: datetime, end: datetime) -> str:
    minutes = max(int((end - start).total_seconds() // 60), 0)
    hours, mins = divmod(minutes, 60)
    return f"{hours} h {mins:02d} min" if hours else f"{mins} min"


def render(session: Session) -> str:
    stamp = "%Y-%m-%d %H:%M"
    lines = [f"## {session.end.strftime('%Y-%m-%d')} \u00b7 {session.title}", ""]
    if session.start:
        lines.append(
            f"**Start:** {session.start.strftime(stamp)} \u00b7 "
            f"**End:** {session.end.strftime(stamp)} \u00b7 "
            f"**Duration:** {format_duration(session.start, session.end)}"
        )
    else:
        lines.append(f"**Start:** not recorded \u00b7 **End:** {session.end.strftime(stamp)}")
    if session.items:
        lines.append("")
        lines.extend(f"- {item}" for item in session.items)
    return "\n".join(lines) + "\n"


def main() -> None:
    sessions = read_sessions()
    parts = [
        "# Work Log\n\n"
        "> AUTO-GENERATED by `generate_log.py` from the Git history. "
        "Do not edit by hand.\n\n"
    ]
    parts.extend(render(s) + "\n" for s in sessions)
    OUTPUT.write_text("".join(parts).rstrip("\n") + "\n", encoding="utf-8", newline="\n")
    print(f"log.md regenerated with {len(sessions)} session(s).")


if __name__ == "__main__":
    main()